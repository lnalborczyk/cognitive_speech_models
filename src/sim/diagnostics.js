/** Post-hoc VTL area-function measurements; not closure labels supplied by VTL.
 * Exclude the posterior 25% to reduce glottal/pharyngeal minima.
 * Candidate closure criterion is configurable and speaker-dependent.
 */
export function oralMinimum(sample,{posteriorFraction=.25}={}){
 const lengths=sample?.lengths_cm,areas=sample?.areas_cm2;
 if(!Array.isArray(lengths)||!Array.isArray(areas)||lengths.length!==areas.length)return null;
 const total=lengths.reduce((s,l)=>s+(Number.isFinite(l)&&l>0?l:0),0);
 if(total<=0)return null;
 let distance=0,best=Infinity,position=NaN;
 for(let i=0;i<lengths.length;i++){
  const length=lengths[i];const x=(distance+length/2)/total;distance+=length;
  if(x<posteriorFraction || !Number.isFinite(areas[i])||areas[i]<0)continue;
  if(areas[i]<best){best=areas[i];position=x;}
 }
 return Number.isFinite(best)?{area_cm2:best,relativePosition:position}:null;
}
export function constrictionSeries(geometry,{closureThreshold=.08}={}){
 return (geometry||[]).map(sample=>{
  const min=oralMinimum(sample);
  return {t:sample.t,minArea_cm2:min?.area_cm2??NaN,
    position:min?.relativePosition??NaN,closureCandidate:!!min&&min.area_cm2<=closureThreshold};
 });
}
export function assessStops(simulation,geometry,{closureThreshold=.08}={}){
 const series=constrictionSeries(geometry,{closureThreshold});
 return simulation.score.gestures.filter(g=>g.kind==='stop').map(g=>{
  // Closure is examined near the intended gesture; duration/position are descriptive.
  const window=series.filter(s=>s.t>=g.start && s.t<=g.end);
  const best=window.reduce((a,b)=>b.minArea_cm2<a.minArea_cm2?b:a,{minArea_cm2:Infinity});
  const hasBest=Number.isFinite(best.minArea_cm2);
  const duration=window.length>1?window.at(-1).t-window[0].t:0;
  return {phone:g.phone,context:g.context,source:g.source,gestureIndex:g.index,
    minOralArea_cm2:hasBest?best.minArea_cm2:null,
    candidateClosure:hasBest?best.minArea_cm2<=closureThreshold:null,
    closestTime_s:hasBest?best.t:null,closureThreshold_cm2:closureThreshold,
    measuredWindow_s:duration};
 });
}
export function acousticEnvelope(wav,{windowMs=16,hopMs=8}={}){
 const {samples,rate}=wav,n=Math.max(8,Math.round(rate*windowMs/1000)),hop=Math.max(1,Math.round(rate*hopMs/1000)),result=[];
 for(let start=0;start+n<=samples.length;start+=hop){
  let sum=0;for(let i=0;i<n;i++)sum+=samples[start+i]*samples[start+i];
  result.push({t:(start+n/2)/rate,rms:Math.sqrt(sum/n)});
 }return result;
}
export function decodeWavBase64(b64){
 // PCM16 little-endian WAV (as generated by this project's VTL adapters).
 const binary=atob(b64),bytes=Uint8Array.from(binary, c=>c.charCodeAt(0));
 const view=new DataView(bytes.buffer);
 if(binary.slice(0,4)!=='RIFF'||binary.slice(8,12)!=='WAVE')throw Error('Not a WAV file');
 const rate=view.getUint32(24,true),bits=view.getUint16(34,true);
 if(bits!==16||view.getUint16(22,true)!==1)throw Error('Expected mono PCM16 WAV');
 let pos=12,dataStart=-1,length=0;
 while(pos+8<=bytes.length){
  const id=binary.slice(pos,pos+4),size=view.getUint32(pos+4,true);
  if(id==='data'){dataStart=pos+8;length=size;break;}
  pos+=8+size+(size%2);
 }
 if(dataStart<0||dataStart+length>bytes.length)throw Error('Invalid WAV data chunk');
 const samples=new Float32Array(length/2);
 for(let i=0;i<samples.length;i++)samples[i]=view.getInt16(dataStart+2*i,true)/32768;
 return {samples,rate};
}
/** Simple deterministic STFT with a precomputed DFT table. Used only for plots. */
export function spectrogram(wav,{fftSize=256,targetRate=8000,hop=128,maxFrames=300}={}){
 const skip=Math.max(1,Math.round(wav.rate/targetRate)),sr=wav.rate/skip;
 const n=Math.floor(wav.samples.length/skip),out=[];
 const cos=new Float64Array((fftSize/2)*fftSize),sin=new Float64Array(cos.length);
 for(let k=0;k<fftSize/2;k++)for(let i=0;i<fftSize;i++){
  const ix=k*fftSize+i,angle=2*Math.PI*k*i/fftSize;
  cos[ix]=Math.cos(angle);sin[ix]=Math.sin(angle);
 }
 const frames=Math.min(maxFrames,Math.max(0,Math.floor((n-fftSize)/hop)+1));
 for(let frame=0;frame<frames;frame++){
  const offset=frame*hop,bands=new Array(fftSize/2);
  for(let k=0;k<fftSize/2;k++){
   let re=0,im=0;const base=k*fftSize;
   for(let i=0;i<fftSize;i++){
    const v=wav.samples[(offset+i)*skip]*(.5-.5*Math.cos(2*Math.PI*i/(fftSize-1)));
    re+=v*cos[base+i];im-=v*sin[base+i];
   }
   bands[k]=20*Math.log10(Math.max(1e-7,Math.hypot(re,im)/fftSize));
  }
  out.push({t:(offset+fftSize/2)/sr,bands});
 }
 return {frames:out,frequencyMax:sr/2,duration:wav.samples.length/wav.rate};
}
